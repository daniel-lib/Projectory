-- Apply this PostgreSQL schema change before deploying the guest-access code.
CREATE TABLE guest_workspace (
    workspace_id VARCHAR(36) PRIMARY KEY,
    invite_code_hash VARCHAR(64) NOT NULL UNIQUE,
    invite_redeemed BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_guest_workspace_expiry ON guest_workspace (expires_at);

CREATE TABLE guest_participant (
    participant_id VARCHAR(36) PRIMARY KEY,
    workspace_id VARCHAR(36) NOT NULL REFERENCES guest_workspace(workspace_id) ON DELETE CASCADE,
    display_name VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_guest_participant_workspace UNIQUE (participant_id, workspace_id)
);

CREATE INDEX idx_guest_participant_workspace ON guest_participant (workspace_id);

CREATE TABLE guest_project (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id VARCHAR(36) NOT NULL REFERENCES guest_workspace(workspace_id) ON DELETE CASCADE,
    created_by VARCHAR(36) NOT NULL,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(1000),
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_guest_project_workspace UNIQUE (project_id, workspace_id),
    CONSTRAINT fk_guest_project_creator FOREIGN KEY (created_by, workspace_id)
        REFERENCES guest_participant(participant_id, workspace_id)
);

CREATE INDEX idx_guest_project_workspace ON guest_project (workspace_id);

CREATE TABLE guest_task (
    task_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id VARCHAR(36) NOT NULL REFERENCES guest_workspace(workspace_id) ON DELETE CASCADE,
    project_id BIGINT NOT NULL,
    assignee_id VARCHAR(36),
    title VARCHAR(120) NOT NULL,
    description VARCHAR(1000),
    status VARCHAR(32) NOT NULL,
    CONSTRAINT fk_guest_task_project FOREIGN KEY (project_id, workspace_id)
        REFERENCES guest_project(project_id, workspace_id) ON DELETE CASCADE,
    CONSTRAINT fk_guest_task_assignee FOREIGN KEY (assignee_id, workspace_id)
        REFERENCES guest_participant(participant_id, workspace_id)
);

CREATE INDEX idx_guest_task_workspace ON guest_task (workspace_id);

CREATE TABLE guest_connection (
    connection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id VARCHAR(36) NOT NULL REFERENCES guest_workspace(workspace_id) ON DELETE CASCADE,
    sender_id VARCHAR(36) NOT NULL,
    receiver_id VARCHAR(36) NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_guest_connection_direction UNIQUE (workspace_id, sender_id, receiver_id),
    CONSTRAINT fk_guest_connection_sender FOREIGN KEY (sender_id, workspace_id)
        REFERENCES guest_participant(participant_id, workspace_id),
    CONSTRAINT fk_guest_connection_receiver FOREIGN KEY (receiver_id, workspace_id)
        REFERENCES guest_participant(participant_id, workspace_id)
);

CREATE TABLE guest_todo_collection (
    collection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id VARCHAR(36) NOT NULL REFERENCES guest_workspace(workspace_id) ON DELETE CASCADE,
    created_by VARCHAR(36) NOT NULL,
    title VARCHAR(40) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_guest_collection_workspace UNIQUE (collection_id, workspace_id),
    CONSTRAINT fk_guest_collection_creator FOREIGN KEY (created_by, workspace_id)
        REFERENCES guest_participant(participant_id, workspace_id)
);

CREATE INDEX idx_guest_todo_collection_workspace ON guest_todo_collection (workspace_id);

CREATE TABLE guest_todo_item (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id VARCHAR(36) NOT NULL REFERENCES guest_workspace(workspace_id) ON DELETE CASCADE,
    collection_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    completed BOOLEAN NOT NULL,
    CONSTRAINT fk_guest_todo_collection FOREIGN KEY (collection_id, workspace_id)
        REFERENCES guest_todo_collection(collection_id, workspace_id) ON DELETE CASCADE
);

CREATE INDEX idx_guest_todo_item_workspace ON guest_todo_item (workspace_id);

CREATE TABLE system_access_tracker (
    access_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_address VARCHAR(45) NOT NULL,
    user_agent VARCHAR(1024),
    browser_type VARCHAR(64),
    operating_system VARCHAR(64),
    guest_access BOOLEAN NOT NULL,
    actor_identifier VARCHAR(100),
    accessed_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_system_access_tracker_accessed_at ON system_access_tracker (accessed_at);
CREATE INDEX idx_system_access_tracker_actor_identifier ON system_access_tracker (actor_identifier);
